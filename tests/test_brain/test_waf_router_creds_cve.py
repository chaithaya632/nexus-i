class TestWAFBypassLibrary:
    def test_empty_waf_name_returns_generic_not_cloudflare(self) -> None:
        lib = WAFBypassLibrary()
        res = lib.get_bypasses("")
        techniques = {r["technique"] for r in res}
        assert "origin_ip_leak" not in techniques
        assert "encoding_layers" in techniques

    def test_deep_copy_isolation(self) -> None:
        lib1 = WAFBypassLibrary()
        res = lib1.get_bypasses("cloudflare")
        res[0]["technique"] = "MUTATED"
        lib1._bypasses["cloudflare"].append({"technique": "extra", "description": "x", "tool": "y"})

        lib2 = WAFBypassLibrary()
        assert BUILTIN_BYPASSES["cloudflare"][0]["technique"] == "origin_ip_leak"
        assert all(t["technique"] != "extra" for t in lib2.get_bypasses("cloudflare"))

    def test_identify_waf_headers_and_body(self) -> None:
        lib = WAFBypassLibrary()
        assert lib.identify_waf({"CF-RAY": "12345"}) == "cloudflare"
        assert lib.identify_waf({}, body="Attention Required! | Cloudflare") == "cloudflare"
        assert lib.identify_waf({}, body="Incapsula incident ID: 999") == "imperva"
        assert lib.identify_waf({}, body="Blocked by ModSecurity") == "modsecurity"
        assert lib.identify_waf({}, body="Generated by Wordfence") == "wordfence"
        assert lib.identify_waf({"Server": "nginx"}, body="Hello world") == "unknown"


class TestServiceRouter:
    def test_deep_copy_isolation(self) -> None:
        r1 = ServiceRouter()
        http_route = r1.route("http")
        http_route["tools"].append("mutated_tool")
        assert "mutated_tool" not in DEFAULT_ROUTING["http"]["tools"]
        assert "mutated_tool" not in ServiceRouter().route("http")["tools"]

    def test_longest_match_prefers_https_over_http(self) -> None:
        r = ServiceRouter()
        assert "sslyze" in r.route("https")["tools"]
        assert "sslyze" in r.route("https-alt")["tools"]
        assert "sslyze" not in r.route("http-alt")["tools"]
        assert r.route("") == {"tools": ["nmap", "nuclei"], "checks": ["cve_scan"]}


class TestCredentialDB:
    def test_load_from_directory_validates_malformed_entries(self, tmp_path: Path) -> None:
        cred_dir = tmp_path / "credentials"
        cred_dir.mkdir(parents=True)
        (cred_dir / "custom.yaml").write_text(
            "myproduct:\n"
            "  - 'not_a_dict'\n"
            "  - {bad_key: 123}\n"
            "  - {service: 'http', username: 'svc', password: 'pw'}\n",
            encoding="utf-8",
        )
        db = CredentialDB()
        before = db.count
        db.load_from_directory(tmp_path)
        assert db.count == before + 1
        hits = db.lookup(service="http", product="myproduct")
        assert len(hits) == 1
        assert hits[0]["username"] == "svc"

    def test_to_hydra_format_guards_empty_user_or_pass(self) -> None:
        db = CredentialDB()
        hydra_txt = db.to_hydra_format()
        for line in hydra_txt.splitlines():
            user, pw = line.split(":", 1)
            assert user != "" and pw != ""
        assert BUILTIN_CREDENTIALS[0]["username"] == "admin"


class TestCVESync:
    def test_import_merges_existing_catalogs(self, tmp_path: Path) -> None:
        import yaml

        kev1 = {
            "vulnerabilities": [
                {
                    "cveID": "CVE-2024-11111",
                    "vendorProject": "VendorA",
                    "product": "ProdA",
                    "shortDescription": "First",
                }
            ]
        }
        kev2 = {
            "vulnerabilities": [
                {
                    "cveID": "CVE-2024-22222",
                    "vendorProject": "VendorB",
                    "product": "ProdB",
                    "shortDescription": "Second",
                }
            ]
        }
        import_cisa_kev_data(kev1, tmp_path)
        _, dest = import_cisa_kev_data(kev2, tmp_path)
        merged = yaml.safe_load(dest.read_text(encoding="utf-8"))["cves"]
        assert "CVE-2024-11111" in merged
        assert "CVE-2024-22222" in merged

        nvd1 = {
            "vulnerabilities": [
                {"cve": {"id": "CVE-2024-33333", "descriptions": [{"lang": "en", "value": "A"}]}}
            ]
        }
        nvd2 = {
            "vulnerabilities": [
                {"cve": {"id": "CVE-2024-44444", "descriptions": [{"lang": "en", "value": "B"}]}}
            ]
        }
        import_nvd_json_data(nvd1, tmp_path)
        _, ndest = import_nvd_json_data(nvd2, tmp_path)
        nmerged = yaml.safe_load(ndest.read_text(encoding="utf-8"))["cves"]
        assert "CVE-2024-33333" in nmerged
        assert "CVE-2024-44444" in nmerged

    @pytest.mark.asyncio
    async def test_sync_cisa_kev_validates_https_and_size_cap(self, tmp_path: Path) -> None:
        with pytest.raises(ValueError, match="https://"):
            await sync_cisa_kev(tmp_path, url="http://example.com/kev.json")

        # Mock oversized response
        mock_resp = MagicMock()
        mock_resp.url = "https://www.cisa.gov/feed.json"
        mock_resp.headers = {"content-length": str(999999999)}
        mock_resp.raise_for_status = MagicMock()

        stream_cm = AsyncMock()
        stream_cm.__aenter__.return_value = mock_resp
        stream_cm.__aexit__.return_value = False

        client_inst = AsyncMock()
        client_inst.stream = MagicMock(return_value=stream_cm)
        client_cm = AsyncMock()
        client_cm.__aenter__.return_value = client_inst
        client_cm.__aexit__.return_value = False

        with patch("nexus.brain.cve_sync.httpx.AsyncClient", return_value=client_cm):
            with pytest.raises(ValueError, match="maximum allowed size"):
                await sync_cisa_kev(tmp_path, max_bytes=1024)


class TestBrainPrecisionFixes:
    def test_version_patch_letters_and_no_loose_substring(self) -> None:
        assert _version_in_range("OpenSSL 1.1.1", ">=1.1.1,<1.1.1t") is True
        assert _version_in_range("OpenSSL 1.1.1s", ">=1.1.1,<1.1.1t") is True
        assert _version_in_range("OpenSSL 1.1.1t", ">=1.1.1,<1.1.1t") is False
        assert _version_in_range("OpenSSL 1.1.1t", ">=1.1.1,<1.1.1w") is True

        kg = KnowledgeGraph()
        kg.load_from_directory(
            Path(__file__).resolve().parents[2] / "nexus" / "brain" / "knowledge"
        )
        # Should group under family 'apache-httpd' and NOT match loose substring '2.4'
        assert kg.get_vulns_for_service("apache-httpd", "2.4") == []
        assert any(
            v.cve == "CVE-2021-41773" for v in kg.get_vulns_for_service("apache-httpd", "2.4.49")
        )

    def test_remediation_case_insensitive_and_safe_cwe22(self) -> None:
        rem = RemediationDB()
        assert rem.get("cwe-89") is not None
        assert rem.lookup("Cwe-79") is not None
        cwe22 = rem.get("cwe-22")
        assert cwe22 is not None
        assert "is_relative_to" in cwe22.code_examples["python"]
        assert ".startswith" not in cwe22.code_examples["python"]

    def test_taxonomy_word_boundaries_and_hyphens(self) -> None:
        tax = TaxonomyMapper()
        assert tax.classify_owasp("Reflected cross-site scripting in search") == "A03"
        assert tax.classify_owasp("Cross site scripting in comment") == "A03"
        # 'ssl' should not match inside 'openssl'
        assert tax.classify_owasp("OpenSSL package inventory") != "A02"

    def test_payloads_single_pass_case_insensitive_and_non_bmp_unicode(self) -> None:
        db = PayloadDB()
        p = Payload(
            name="test_p",
            category="SQLi",
            platform="Linux",
            language="Python",
            template="{LHOST}:{LPORT}",
            tags=["WAF-Bypass"],
        )
        db.add_payload(p)
        assert (
            len(
                db.search(
                    category="sqli", platform="linux", language="python", keyword="waf-bypass"
                )
            )
            == 1
        )
        assert db.render(p, {"LHOST": "{LPORT}", "LPORT": "4444"}) == "{LPORT}:4444"
        assert encode_unicode("😀") == "\\ud83d\\ude00"

    def test_vector_search_versions_cve_tokens_dedup_and_single_doc_idf(self) -> None:
        vs = VectorSearch()
        vs.add_entry("CVE-2021-44228", "Apache Log4j 2.14.1 JNDI RCE")
        vs.add_entry("CVE-2021-44228", "Apache Log4j 2.14.1 CVE-2021-44228 JNDI RCE")
        assert vs.entry_count == 1
        vs.build_index()
        assert vs._idf is not None and float(vs._idf.min()) >= 1.0
        assert len(vs.search("44228")) == 1
        assert len(vs.search("2.14.1")) == 1
